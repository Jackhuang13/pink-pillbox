export function translate(
  lang: Lang,
  key: I18nKey,
  vars?: Record<string, string | number>
): string {
  let text: string = (lang === 'zh' ? zh : en)[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}
